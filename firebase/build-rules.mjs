#!/usr/bin/env node
/**
 * Builds the one Realtime Database ruleset of the-equal-lens from each app's
 * piece (knowledge/playbooks/firebase.md).
 *
 * A database has one rules file, and every Equal Lens app shares the project's
 * one database (the owner, 3 October 2026: the free plan, one shared database).
 * So each app keeps its own piece, `database.rules.json` in its own repo, where
 * it is tested, and names only the top-level nodes `apps.json` registers to it.
 * This takes every piece from its repo's main on GitHub, refuses a node at the
 * root, a node not registered to the app, a node two apps claim and a
 * registered node a piece is missing, and on any problem writes nothing and
 * lists every problem at once. It runs before every deploy (firebase.json), so
 * what goes live is always what each app has merged.
 *
 *   node build-rules.mjs           the pieces from each repo's main on GitHub
 *   node build-rules.mjs --local   the pieces from ~/<repo> checkouts, to try a
 *                                  change before it is merged (never deployed:
 *                                  the deploy builds again from main)
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))

/** The rules language's JSON, with its block and line comments taken out. */
export const stripComments = (text) => {
  let out = ''
  let inString = false
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i]
    const next = text[i + 1]
    if (inString) {
      out += c
      if (c === '\\') {
        out += next ?? ''
        i += 1
      } else if (c === '"') inString = false
    } else if (c === '"') {
      inString = true
      out += c
    } else if (c === '/' && next === '*') {
      const end = text.indexOf('*/', i + 2)
      i = end < 0 ? text.length : end + 1
    } else if (c === '/' && next === '/') {
      const end = text.indexOf('\n', i)
      i = end < 0 ? text.length : end - 1
    } else out += c
  }
  return out
}

/** The merged ruleset, or every problem with the pieces. */
export const merge = (apps, pieces) => {
  const problems = []
  const owner = new Map()
  const rules = {}
  apps.forEach((app, n) => {
    let piece
    try {
      piece = JSON.parse(stripComments(pieces[n]))
    } catch (e) {
      problems.push(`${app.name}: its rules are not JSON (${e.message})`)
      return
    }
    const nodes = piece && typeof piece.rules === 'object' && piece.rules ? piece.rules : null
    if (!nodes) {
      problems.push(`${app.name}: no "rules" object`)
      return
    }
    for (const [key, value] of Object.entries(nodes)) {
      if (key.startsWith('.') || key.startsWith('$')) problems.push(`${app.name}: ${key} at the root would apply to every app`)
      else if (!app.nodes.includes(key)) problems.push(`${app.name}: ${key} is not registered to it in apps.json (${app.nodes.join(', ')})`)
      else if (owner.has(key)) problems.push(`${app.name}: ${key} is already ${owner.get(key)}'s`)
      else {
        owner.set(key, app.name)
        rules[key] = value
      }
    }
    for (const node of app.nodes) if (!(node in nodes)) problems.push(`${app.name}: registered node ${node} is not in its rules`)
  })
  return { rules, problems }
}

const fetchPiece = (app, local) => {
  if (local) {
    const dir = join(homedir(), app.repo.split('/')[1])
    const sha = execFileSync('git', ['-C', dir, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim()
    return { text: readFileSync(join(dir, app.rules), 'utf8'), from: `${dir} at ${sha} (local, not deployable)` }
  }
  const sha = execFileSync('gh', ['api', `repos/${app.repo}/commits/main`, '--jq', '.sha'], { encoding: 'utf8' }).trim()
  const text = execFileSync(
    'gh',
    ['api', '-H', 'Accept: application/vnd.github.raw', `repos/${app.repo}/contents/${app.rules}?ref=${sha}`],
    { encoding: 'utf8' },
  )
  return { text, from: `${app.repo}@${sha.slice(0, 7)}, ${app.rules}` }
}

const main = () => {
  const local = process.argv.includes('--local')
  const { apps } = JSON.parse(readFileSync(join(here, 'apps.json'), 'utf8'))
  const fetched = apps.map((app) => fetchPiece(app, local))
  const { rules, problems } = merge(
    apps,
    fetched.map((f) => f.text),
  )
  if (problems.length) {
    console.error(`build-rules: refused, nothing written. ${problems.length} problem${problems.length === 1 ? '' : 's'}:`)
    for (const p of problems) console.error(`  ${p}`)
    process.exit(1)
  }
  const header = [
    '  /* GENERATED by firebase/build-rules.mjs: do not edit. Each app keeps its',
    '     piece in its own repo (knowledge/playbooks/firebase.md). Built from:',
    ...apps.map((app, n) => `       ${app.name}: ${fetched[n].from}`),
    '  */',
  ]
  const body = JSON.stringify({ rules }, null, 2).split('\n')
  writeFileSync(join(here, 'database.rules.json'), [body[0], ...header, ...body.slice(1)].join('\n') + '\n')
  console.log(`build-rules: ${Object.keys(rules).length} nodes from ${apps.length} apps written to firebase/database.rules.json`)
  for (const [n, app] of apps.entries()) console.log(`  ${app.name}: ${app.nodes.join(', ')} from ${fetched[n].from}`)
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main()
